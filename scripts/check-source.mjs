import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const code=await readFile('intelligent-contract/contracts/signal_ledger.py');
const manifest=JSON.parse(await readFile('deployment.json','utf8'));
const hash=createHash('sha256').update(code).digest('hex');
const expected=manifest.candidateRemediation?.sourceSha256 ?? manifest.sourceSha256;
if(hash!==expected)throw new Error('Canonical/candidate source SHA256 mismatch');
if(manifest.chainId!==61999 || manifest.rpc!=='https://studio.genlayer.com/api')throw new Error('Wrong network');
console.log('PASS candidate source SHA256: '+hash);
if(manifest.candidateRemediation?.status==='PENDING_DEPLOYMENT')console.log('NOTE candidate is not deployed; runtime verification remains disabled.');
